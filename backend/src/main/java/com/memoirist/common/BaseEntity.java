package com.memoirist.common;

import jakarta.persistence.Column;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Transient;
import java.util.Objects;
import java.util.UUID;
import org.hibernate.Hibernate;
import org.springframework.data.domain.Persistable;

/**
 * The UUID {@code id} that every entity has (D-12).
 *
 * <p>The id is set in the constructor, either the client's own (so Phase 5 can create entries offline) or
 * {@code UUID.randomUUID()}, never generated by the database. That creates a problem for {@code save()}: Spring Data
 * decides between {@code persist} (INSERT) and {@code merge} (SELECT, then INSERT or UPDATE) by asking whether the
 * entity is new, and for an entity whose id is already set the answer it guesses is "no". Implementing
 * {@link Persistable} lets the entity answer for itself, so a new row costs one INSERT and no SELECT.
 *
 * <p>Equality is the id: ids are assigned once and never change, so {@code equals} and {@code hashCode} are stable
 * from construction onwards, which a {@code Set<Tag>} or a {@code HashMap} of entities needs.
 */
@MappedSuperclass
public abstract class BaseEntity implements Persistable<UUID> {

    @Id
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    // TODO(human) PRACTICE: make save() INSERT an entity whose id was set in the constructor, with no SELECT first.
    //   A new entity must answer isNew() == true, and one that came from the database (or was just saved) must
    //   answer false. Which JPA callbacks tell you "this row exists now", and what must the field not be? (JPA
    //   would try to store it as a column.) PersistableInsertTest shows the SQL, so you can see when it goes wrong.
    // Hint: D-12 and .claude/rules/backend.md (Persistence). Hibernate creates entities loaded from the database
    //   through the protected no-argument constructor, then fills in the fields.
    // ┌── ANSWER ▼ (delete or fold this block, write your own, then compare) ──
    @Transient
    private boolean isNew = true;

    @Override
    public boolean isNew() {
        return isNew;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }
    // └── END ANSWER ▲ ──

    /** For Hibernate, which fills in the fields after loading a row. Application code uses the other constructor. */
    protected BaseEntity() {}

    protected BaseEntity(UUID id) {
        this.id = Objects.requireNonNull(id, "id");
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        // Hibernate may hand out a proxy subclass, so compare the real classes and go through getId(): a proxy's
        // own id field is not filled in until it is loaded.
        if (!(other instanceof BaseEntity that) || Hibernate.getClass(this) != Hibernate.getClass(that)) {
            return false;
        }
        return getId() != null && getId().equals(that.getId());
    }

    @Override
    public int hashCode() {
        return Objects.hashCode(getId());
    }
}
